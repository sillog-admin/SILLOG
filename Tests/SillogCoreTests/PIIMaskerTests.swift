    /// Each of these took seconds or more before: the email rule on long runs without @, the address detector on number
    /// lists and long lines, and the jwt, kr-key-value and key-value lookaheads on repeated starts.
    func testAdversarialInputsStayFast() {
        let inputs = [
            String(repeating: "Ab-Cd-Ef-Gh-12-", count: 2000),
            "Total " + (1...300).map(String.init).joined(separator: " "),
            String(repeating: "강남구 ", count: 5000),
            String(repeating: "eyJ-", count: 5000),
            String(repeating: "OTP", count: 7000),
            String(repeating: "pw=", count: 7000),
        ]
        for text in inputs {
            let start = Date()
            _ = PIIMasker.mask(text)
            XCTAssertLessThan(Date().timeIntervalSince(start), 2, String(text.prefix(20)))
        }
    }

    func testSendsTextAsIsWhenOff() {
        PIIMasker.enabled = false
        defer { PIIMasker.enabled = true }
        XCTAssertEqual(PIIMasker.mask("전화 010-1234-5678"), "전화 010-1234-5678")
    }

